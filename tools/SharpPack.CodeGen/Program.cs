using System.Globalization;
using System.Text;

const string command = "dotnet run --project tools/SharpPack.CodeGen --";
const string header = "// Generated by SharpPack.CodeGen. Change the tool and run its update command.\n\n";
if (args.Length != 1 || args[0] is not ("verify" or "update"))
{
    Console.Error.WriteLine($"Usage: {command} verify|update");
    return 2;
}

var root = FindRepositoryRoot();
if (root is null)
{
    Console.Error.WriteLine("Run from the SharpPack repository.");
    return 2;
}

CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
(string Path, Func<string> Render)[] outputs =
[
    ("SharpPackReader.Unmanaged.cs", UnmanagedOverloads.RenderReader),
    ("SharpPackWriter.Unmanaged.cs", UnmanagedOverloads.RenderWriter),
    ("FormatterResolver.WellKnownTypes.cs", WellKnownFormatters.Render),
    ("Formatters/TupleFormatter.cs", TupleFormatters.Render),
];

var stale = false;
foreach (var (name, render) in outputs)
{
    var relativePath = $"src/SharpPack.Core/{name}";
    var path = Path.Combine(root, relativePath);
    var expected = Encoding.UTF8.GetBytes((header + render()).ReplaceLineEndings("\n"));
    if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(expected))
    {
        continue;
    }

    if (args[0] == "update")
    {
        File.WriteAllBytes(path, expected);
        Console.WriteLine($"Updated {relativePath}");
    }
    else
    {
        Console.Error.WriteLine($"Missing or stale generated file: {relativePath}");
        stale = true;
    }
}

if (stale)
{
    Console.Error.WriteLine($"Regenerate with: {command} update");
    return 1;
}

return 0;

static string? FindRepositoryRoot()
{
    for (DirectoryInfo? directory = new(Environment.CurrentDirectory); directory is not null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "SharpPack.sln")))
        {
            return directory.FullName;
        }
    }

    return null;
}
