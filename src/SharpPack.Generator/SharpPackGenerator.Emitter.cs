    string EmitDeserializeMembersCore(
        MemberMeta[] members,
        string indent,
        bool honorFormatterOverrides)
    {
        // {{Members.Select(x => "                " + x.EmitReadToDeserialize()).NewLine()}}
        var sb = new StringBuilder();
        for (int i = 0; i < members.Length; i++)
        {
            if (honorFormatterOverrides ||
                !(members[i].Kind is MemberKind.Unmanaged or MemberKind.Enum or MemberKind.UnmanagedNullable) ||
                (GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference))
            {
                sb.Append(indent);
                sb.AppendLine(members[i].EmitReadToDeserialize(
                    i,
                    GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference,
                    honorFormatterOverrides));
                continue;
            }

            // search optimization
            var optimizeFrom = i;
            var optimizeTo = i;
            var limit = Math.Min(members.Length, i + 15);
            var dangerous = "";
            for (int j = i; j < limit; j++)
            {
                if (members[j].Kind is MemberKind.Unmanaged or MemberKind.Enum or MemberKind.UnmanagedNullable)
                {
                    if (members[j].Kind is MemberKind.UnmanagedNullable)
                    {
                        dangerous = "Dangerous";
                    }
                    optimizeTo = j;
                    continue;
                }
                else
                {
                    break;
                }
            }

            // write read method
            sb.Append(indent);
            sb.Append($"reader.{dangerous}ReadUnmanaged(");

            for (int index = optimizeFrom; index <= optimizeTo; index++)
            {
                if (index != i)
                {
                    sb.Append(", ");
                }
                sb.Append("out __");
                sb.Append(members[index].Name);
            }
            sb.AppendLine(");");

            i = optimizeTo;
        }

        return sb.ToString();
    }

    string EmitFormatterOverrideDependencyCondition(
        string receiver,
        bool useOptionalState = true)
    {
        var types = new List<ITypeSymbol>();
        foreach (var member in Members)
        {
            if (member.Kind is MemberKind.Blank or MemberKind.CustomFormatter)
            {
                continue;
            }
            AddTypeAndDependencies(member.MemberType);
        }

        var registrations = types
            .Select(static type =>
                type.ToDisplayString(
                    SymbolDisplayFormat.FullyQualifiedFormat))
            .Distinct(StringComparer.Ordinal)
            .Select(type => useOptionalState
                ? $"{receiver}.OptionalState.HasFormatterOverride<{type}>()"
                : $"{receiver}.HasFormatterOverrideDependency<{type}>()");
        var registrationCondition = string.Join(" || ", registrations);
        return registrationCondition;

        void AddTypeAndDependencies(ITypeSymbol type)
        {
            types.Add(type);
            if (type is IArrayTypeSymbol array)
            {
                AddTypeAndDependencies(array.ElementType);
                return;
            }

            if (type is not INamedTypeSymbol named ||
                !named.IsGenericType ||
                !reference.KnownTypes.Contains(named))
            {
                return;
            }

            foreach (var argument in named.TypeArguments)
            {
                AddTypeAndDependencies(argument);
            }
        }
    }

