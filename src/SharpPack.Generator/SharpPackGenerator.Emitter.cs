    {
        var name = serialize
            ? "__SharpPackSerializeWithFormatterOverrides"
            : "__SharpPackDeserializeWithFormatterOverrides";
        while (Symbol.GetAllMembers().Any(member => member.Name == name) ||
               Symbol.TypeParameters.Any(parameter => parameter.Name == name))
