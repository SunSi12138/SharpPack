    string EmitCustomFormatters()
    {
        var sb = new StringBuilder();
        foreach (var item in Members.Where(x => x.Kind == MemberKind.CustomFormatter))
        {
            var attribute = item.CustomFormatterAttribute!;
            var arguments = string.Join(
                ", ",
                attribute.ConstructorArguments.Select(EmitTypedConstant));
            var initializers = attribute.NamedArguments
                .Select(static pair =>
                    $"@{pair.Key} = {EmitTypedConstant(pair.Value)}")
                .ToArray();
            var initializer = initializers.Length == 0
                ? ""
                : $" {{ {string.Join(", ", initializers)} }}";

            sb.AppendLine(
                $"    static readonly {item.CustomFormatterName} __{item.Name}Formatter = " +
                $"new {item.CustomFormatter!.FullyQualifiedToString()}({arguments})" +
                $"{initializer}.GetFormatter();");
        }
        return sb.ToString();
    }

    static string EmitTypedConstant(TypedConstant constant)
    {
        if (constant.IsNull)
        {
            return "null";
        }

        return constant.Kind switch
        {
            TypedConstantKind.Primitive =>
                Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(
                    constant.Value!,
                    quoteStrings: true,
                    useHexadecimalNumbers: false),
            TypedConstantKind.Enum =>
                $"({constant.Type!.FullyQualifiedToString()})" +
                Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(
                    constant.Value!,
                    quoteStrings: false,
                    useHexadecimalNumbers: false),
            TypedConstantKind.Type =>
                $"typeof({((ITypeSymbol)constant.Value!).FullyQualifiedToString()})",
            TypedConstantKind.Array =>
                $"new {((IArrayTypeSymbol)constant.Type!).ElementType.FullyQualifiedToString()}[]" +
                $" {{ {string.Join(", ", constant.Values.Select(EmitTypedConstant))} }}",
            _ => throw new InvalidOperationException(
                $"Unsupported custom formatter attribute argument: {constant.Kind}."),
        };
    }

    string EmitAotFormatterRoots(string indent)
    {
        var formatterTypes = new HashSet<string>(StringComparer.Ordinal);
        var factoryTypes = new HashSet<string>(StringComparer.Ordinal);

        foreach (var member in Members)
        {
            AddFormatterTypes(member.MemberType);
        }

        if (formatterTypes.Count == 0 && factoryTypes.Count == 0)
        {
            return "";
        }

        var sb = new StringBuilder();
        sb.AppendLine(
            $"{indent}if (!global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported)");
        sb.AppendLine($"{indent}{{");
        foreach (var formatterType in formatterTypes.OrderBy(static x => x))
        {
            sb.AppendLine(
                $"{indent}    global::System.GC.KeepAlive(new {formatterType}());");
        }
        foreach (var factoryType in factoryTypes.OrderBy(static x => x))
        {
            sb.AppendLine(
                $"{indent}    global::System.GC.KeepAlive(PreserveFactory<{factoryType}, {factoryType}>());");
            sb.AppendLine(
                $"{indent}    global::System.GC.KeepAlive(typeof({factoryType}).GetMethods(global::System.Reflection.BindingFlags.Static | global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.NonPublic));");
        }
        if (factoryTypes.Count != 0)
        {
            sb.AppendLine();
            sb.AppendLine(
                $"{indent}    static global::System.Func<global::SharpPack.SharpPackFormatter<TValue>> PreserveFactory<TValue, TFactory>()");
            sb.AppendLine(
                $"{indent}        where TFactory : global::SharpPack.ISharpPackFormatterFactory<TValue>");
            sb.AppendLine(
                $"{indent}        => TFactory.CreateFormatter;");
        }
        sb.Append($"{indent}}}");
        return sb.ToString();

        void AddFormatterTypes(ITypeSymbol type)
        {
            if (reference.KnownTypes.GetNonDefaultFormatterName(type) is { } formatter)
            {
                formatterTypes.Add(formatter);
            }

            if (type.TryGetSharpPackableType(
                    reference,
                    out var generateType,
                    out _) &&
                generateType != GenerateType.NoGenerate)
            {
                factoryTypes.Add(type.FullyQualifiedToString());
            }

            if (type is IArrayTypeSymbol array)
            {
                AddFormatterTypes(array.ElementType);
            }
            else if (type is INamedTypeSymbol named)
            {
                foreach (var argument in named.TypeArguments)
                {
                    AddFormatterTypes(argument);
                }
            }
        }
    }

    string EmitSerializeBody()
    {
        if (this.GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference)
        {
            return Members.All(x =>
                x.Kind is MemberKind.Unmanaged
                    or MemberKind.String
                    or MemberKind.Enum
                    or MemberKind.UnmanagedArray
                    or MemberKind.UnmanagedNullable
                    or MemberKind.Blank)
                ? EmitVersionTorelantSerializeBodyOptimized()
                : EmitVersionTorelantSerializeBody(
                    honorFormatterOverrides: false);
        }

        return EmitObjectSerializeBody(honorFormatterOverrides: false);
    }

    string EmitExactSizeSerializeMethod()
    {
        var captureMembers = Members
            .Select((member, index) => member.Kind == MemberKind.String
                ? $"""
        var __value{index} = this.@{member.Name};
        var __utf8Length{index} = __value{index} is null || __value{index}.Length == 0
            ? 0
            : global::System.Text.Encoding.UTF8.GetByteCount(__value{index});
"""
                : $"        var __value{index} = this.@{member.Name};")
            .NewLine();
        var sizeTerms = Members
            .Select((member, index) => member.Kind switch
            {
                MemberKind.Unmanaged or
                MemberKind.Enum or
                MemberKind.UnmanagedNullable =>
                    $"global::System.Runtime.CompilerServices.Unsafe.SizeOf<{member.MemberType.FullyQualifiedToString()}>()",
                MemberKind.String =>
                    $"(__value{index} is null || __value{index}.Length == 0 ? 4L : (long)__utf8Length{index} + 8)",
                MemberKind.UnmanagedArray =>
                    $"(__value{index} is null || __value{index}.Length == 0 ? 4L : (long)__value{index}.Length * global::System.Runtime.CompilerServices.Unsafe.SizeOf<{((IArrayTypeSymbol)member.MemberType).ElementType.FullyQualifiedToString()}>() + 4)",
                _ => throw new InvalidOperationException(),
            });
        var writeMembers = Members
            .Select((member, index) => member.Kind switch
            {
                MemberKind.Unmanaged or MemberKind.Enum =>
                    $"        writer.WriteUnmanaged(__value{index});",
                MemberKind.UnmanagedNullable =>
                    $"        writer.DangerousWriteUnmanaged(__value{index});",
                MemberKind.String =>
                    $"        writer.WriteUtf8Exact(__value{index}, __utf8Length{index});",
                MemberKind.UnmanagedArray =>
                    $"        writer.WriteUnmanagedArray(__value{index});",
                _ => throw new InvalidOperationException(),
            })
            .NewLine();
        var sizeExpression = string.Join(
            " + " + Environment.NewLine + "            ",
            sizeTerms);

        return $$"""

    [global::SharpPack.Internal.Preserve]
    byte[] global::SharpPack.ISharpPackExactSizeSerializable<{{TypeName}}>.SerializeExact()
    {
{{captureMembers}}
        var size = 1L +
            {{sizeExpression}};
        if ((ulong)size > (ulong)global::System.Array.MaxLength)
        {
            global::SharpPack.SharpPackSerializationException.ThrowSizeOverflow();
        }
        var buffer = global::System.GC.AllocateUninitializedArray<byte>((int)size);
        var bufferWriter =
            new global::SharpPack.Internal.SharpPackExactArrayBufferWriter(buffer);
        var writer = global::SharpPack.SharpPackSerializer.CreateExactWriter(
            ref bufferWriter);
        writer.WriteObjectHeader({{Members.Length}});
{{writeMembers}}
        writer.Flush();
        return bufferWriter.GetFilledBuffer();
    }
""";
    }

