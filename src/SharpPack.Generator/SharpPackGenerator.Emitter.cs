    public void Emit(StringBuilder writer, IGeneratorContext context)
        => Emit(writer, context, SerializationPlanner.Plan(TypeShape.Create(Symbol, this)));

    internal void Emit(StringBuilder writer, IGeneratorContext context, SerializationPlan plan)
    {
        var shape = plan.Shape;
        if (shape.IsUnion)
        {
            writer.AppendLine(EmitUnionTemplate(context, shape));
            return;
        }

        if (shape.GenerateType == GenerateType.Collection)
        {
            writer.AppendLine(EmitGenericCollectionTemplate(context));
            return;
        }

        var serializeBody = "";
        var deserializeBody = "";
        var formatterOverrideMethods = "";
        var contextFormatterTypeName = "__SharpPackContextFormatter";
        while (Symbol.GetAllMembers().Any(
                   member => member.Name == contextFormatterTypeName) ||
               Symbol.TypeParameters.Any(
                   parameter => parameter.Name == contextFormatterTypeName))
        {
            contextFormatterTypeName += "_";
        }
        if (IsUnmanagedType)
        {
            serializeBody = $$"""
        writer.WriteUnmanaged(value);
""";
            deserializeBody = $$"""
        reader.ReadUnmanaged(out value);
""";
        }
        else
        {
            var wireMembers = plan.WireSlots.Select(slot => slot.DeclaredMemberIndex is int index
                ? Members[index] : MemberMeta.CreateEmpty(slot.Position)).ToArray();
            serializeBody = EmitSerializeBody(wireMembers);
            deserializeBody = EmitDeserializeBodyCore(wireMembers, honorFormatterOverrides: false);
            formatterOverrideMethods = EmitFormatterOverrideMethods(
                contextFormatterTypeName, shape, wireMembers);
        }

        var classOrStructOrRecord = (IsRecord, IsValueType) switch
        {
            (true, true) => "record struct",
            (true, false) => "record",
            (false, true) => "struct",
            (false, false) => "class",
        };

        var containingTypes = new List<INamedTypeSymbol>();
        var containingType = Symbol.ContainingType;
        while (containingType is not null)
        {
            containingTypes.Add(containingType);
            containingType = containingType.ContainingType;
        }
        containingTypes.Reverse();

        var nullable = IsValueType ? "" : "?";

        var staticSharpPackableMethod =
            $"static void ISharpPackable<{TypeName}>.";
        const string scopedRef = "scoped ref";
        const string constraint = "";
        var fixedSizeInterface = "";
        var fixedSizeMethod = "";
        var exactSizeInterface = "";
        var exactSizeMethod = "";
        if (plan.RootFastPath == RootFastPath.FixedSize)
        {
            var sizeOf = string.Join(
                " + ",
                shape.Members.Select(member =>
                    $"System.Runtime.CompilerServices.Unsafe.SizeOf<{member.TypeName}>()"));
            var headerPlus = shape.Members.Length == 0 ? "1" : "1 + ";
            fixedSizeInterface = ", global::SharpPack.IFixedSizeSharpPackable";
            fixedSizeMethod = $$"""

    [global::SharpPack.CompilerServices.Preserve]
    static int global::SharpPack.IFixedSizeSharpPackable.Size => {{headerPlus}}{{sizeOf}};

""";
        }

        else if (plan.RootFastPath == RootFastPath.ExactSize)
        {
            exactSizeInterface =
                $", global::SharpPack.ISharpPackExactSizeSerializable<{TypeName}>";
            exactSizeMethod = EmitExactSizeSerializeMethod();
        }
        const string serializeMethodSignarture =
            "Serialize<TBufferWriter>(ref SharpPackWriter<TBufferWriter>";

        foreach (var container in containingTypes)
        {
            writer.AppendLine(EmitPartialTypeDeclaration(container));
            writer.AppendLine(EmitTypeParameterConstraints(
                container.TypeParameters));
            writer.AppendLine("{");
        }

        var contextFactoryInterface =
            $", global::SharpPack.ISharpPackFormatterFactory<{TypeName}>" +
            $", global::SharpPack.ISharpPackContextFormatterFactory<{TypeName}>";
        var contextDependencyCondition = IsUnmanagedType
            ? ""
            : EmitFormatterOverrideDependencyCondition(
                Members, "context",
                useOptionalState: false);
        var contextFormatterSelection =
            contextDependencyCondition.Length == 0
                ? $"return new global::SharpPack.Formatters.SharpPackableFormatter<{TypeName}>();"
                : $$"""
        if ({{contextDependencyCondition}})
        {
            return new {{contextFormatterTypeName}}();
        }
        return new global::SharpPack.Formatters.SharpPackableFormatter<{{TypeName}}>();
""";
        var selfFactoryRoot = GetSelfFactoryRootName();
        var selfFactoryRootRead = EmitFactoryRootRead(selfFactoryRoot);
        var aotFormatterRoots = EmitAotFormatterRoots("        ");
        var aotRootMethodName = "__SharpPackEnsureAotFormatterRoots";
        while (Symbol.GetAllMembers().Any(
                   member => member.Name == aotRootMethodName) ||
               Symbol.TypeParameters.Any(
                   parameter => parameter.Name == aotRootMethodName))
        {
            aotRootMethodName += "_";
        }
        var aotRootCall = aotFormatterRoots.Length == 0
            ? ""
            : $"        {aotRootMethodName}();";
        var aotRootMethod = aotFormatterRoots.Length == 0
            ? ""
            : $$"""

    [global::SharpPack.CompilerServices.Preserve]
    static void {{aotRootMethodName}}()
    {
{{aotFormatterRoots}}
    }
""";
        var contextFactoryMethod = $$"""

    [global::SharpPack.CompilerServices.Preserve]
    static global::SharpPack.SharpPackFormatter<{{TypeName}}> global::SharpPack.ISharpPackFormatterFactory<{{TypeName}}>.CreateFormatter()
    {
{{selfFactoryRootRead}}
{{aotRootCall}}
        return new global::SharpPack.Formatters.SharpPackableFormatter<{{TypeName}}>();
    }

    [global::SharpPack.CompilerServices.Preserve]
    static global::SharpPack.SharpPackFormatter<{{TypeName}}> global::SharpPack.ISharpPackContextFormatterFactory<{{TypeName}}>.CreateFormatter(
        global::SharpPack.SharpPackSerializerContext context)
    {
{{selfFactoryRootRead}}
{{aotRootCall}}
        {{contextFormatterSelection}}
    }
{{aotRootMethod}}
""";

        writer.AppendLine($$"""
partial {{classOrStructOrRecord}} {{TypeName}} : ISharpPackable<{{TypeName}}>{{fixedSizeInterface}}{{exactSizeInterface}}{{contextFactoryInterface}}
{
{{(IsUnmanagedType ? "" : EmitCustomFormatters(shape.Members))}}
    static partial void StaticConstructor();

{{EmitSelfFactoryRoots(selfFactoryRoot, includeContextFactory: true)}}
{{fixedSizeMethod}}
{{exactSizeMethod}}
{{contextFactoryMethod}}
{{formatterOverrideMethods}}

    [global::SharpPack.CompilerServices.Preserve]
    {{staticSharpPackableMethod}}{{serializeMethodSignarture}} writer, {{scopedRef}} {{TypeName}}{{nullable}} value) {{constraint}}
    {
{{EmitCallbacks(shape, CallbackPhase.Serializing)}}
{{serializeBody}}
    END:
{{EmitCallbacks(shape, CallbackPhase.Serialized)}}
        return;
    }

    [global::SharpPack.CompilerServices.Preserve]
    {{staticSharpPackableMethod}}Deserialize(ref SharpPackReader reader, {{scopedRef}} {{TypeName}}{{nullable}} value)
    {
{{EmitCallbacks(shape, CallbackPhase.Deserializing)}}
{{deserializeBody}}
    END:
{{EmitCallbacks(shape, CallbackPhase.Deserialized)}}
        return;
    }

}
""");

        for(int i = 0; i < containingTypes.Count; ++i)
        {
            writer.AppendLine("}");
        }
    }

    private string EmitDeserializeBodyCore(MemberMeta[] members, bool honorFormatterOverrides)
    {
        var count = members.Length;

        var isVersionTolerant = this.GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference;
        var readBeginBody = "";
        var readEndBody = "";
        var commentOutInvalidBody = "";
        var circularReferenceBody = "";
        var circularReferenceBody2 = "";

        if (isVersionTolerant)
        {
            readBeginBody = """
        Span<int> deltas = stackalloc int[count];
        long totalDelta = 0;
        for (int i = 0; i < count; i++)
        {
            deltas[i] = reader.ReadVarIntInt32();
            if (deltas[i] < 0)
            {
                SharpPackSerializationException.ThrowInvalidLength(deltas[i]);
            }
            totalDelta += deltas[i];
        }
        if (totalDelta > reader.Remaining)
        {
            SharpPackSerializationException.ThrowInvalidAdvance();
        }
""";

            readEndBody = """
        if (count == readCount) goto END;

        for (int i = readCount; i < count; i++)
        {
            reader.Advance(deltas[i]);
        }
""";

            commentOutInvalidBody = "// ";
        }
        if (GenerateType == GenerateType.CircularReference)
        {
            circularReferenceBody = $$"""
        uint id;
        if (count == SharpPackCode.ReferenceId)
        {
            id = reader.ReadVarIntUInt32();
            value = ({{TypeName}})reader.OptionalState.GetObjectReference(id);
            goto END;
        }
""";

            circularReferenceBody2 = $$"""
        id = reader.ReadVarIntUInt32();
        if (value == null)
        {
            value = new {{TypeName}}();
        }
        reader.OptionalState.AddObjectReference(id, value);
""";
        }

        return $$"""
        if (!reader.TryReadObjectHeader(out var count))
        {
            value = default!;
            goto END;
        }
{{circularReferenceBody}}
{{readBeginBody}}
{{circularReferenceBody2}}
{{members.Where(x => x.Symbol != null).Select(x => $"        {x.MemberType.FullyQualifiedToString()} __{x.Name};").NewLine()}}

        {{(!isVersionTolerant ? "" : "var readCount = " + count + ";")}}
        if (count == {{count}})
        {
            {{(IsValueType ? "" : "if (value == null)")}}
            {
{{EmitDeserializeMembers(
    members,
    "                ",
    honorFormatterOverrides)}}

                goto NEW;
            }
{{(IsValueType ? "#if false" : "            else")}}
            {
{{members.Where(x => x.Symbol != null).Select(x => $"                __{x.Name} = value.@{x.Name};").NewLine()}}

{{EmitReadRefDeserializeMembers(
    members,
    "                ",
    includeCountJumps: false,
    honorFormatterOverrides)}}

                goto SET;
            }
{{(IsValueType ? "#endif" : "")}}
        }
        {{commentOutInvalidBody}}else if (count > {{count}})
        {{commentOutInvalidBody}}{
            {{commentOutInvalidBody}}SharpPackSerializationException.ThrowInvalidPropertyCount(typeof({{TypeName}}), {{count}}, count);
            {{commentOutInvalidBody}}goto READ_END;
        {{commentOutInvalidBody}}}
        else
        {
            {{(IsValueType ? "" : "if (value == null)")}}
            {
{{members.Where(x => x.Symbol != null).Select(x => $"               __{x.Name} = default!;").NewLine()}}
            }
{{(IsValueType ? "#if false" : "            else")}}
            {
{{members.Where(x => x.Symbol != null).Select(x => $"               __{x.Name} = value.@{x.Name};").NewLine()}}
            }
{{(IsValueType ? "#endif" : "")}}

            if (count == 0) goto SKIP_READ;
{{EmitReadRefDeserializeMembers(
    members,
    "            ",
    includeCountJumps: true,
    honorFormatterOverrides)}}

    SKIP_READ:
            {{(IsValueType ? "" : "if (value == null)")}}
            {
                goto NEW;
            }
{{(IsValueType ? "#if false" : "            else")}}
            {
                goto SET;
            }
{{(IsValueType ? "#endif" : "")}}
        }

    SET:
        {{(!IsUseEmptyConstructor ? "goto NEW;" : "")}}
{{members.Where(x => x.IsAssignable).Select(x => $"        {(IsUseEmptyConstructor ? "" : "// ")}value.@{x.Name} = __{x.Name};").NewLine()}}
        goto READ_END;

    NEW:
        value = {{EmitConstructor(members)}}
        {
{{EmitDeserializeConstruction(members, "            ")}}
        };
{{EmitDeserializeConstructionWithBranching(members, "        ")}}
    READ_END:
{{readEndBody}}
""";
    }

    static string EmitCallbacks(TypeShape shape, CallbackPhase phase)
        => shape.IsUnmanaged ? "" : shape.Callbacks.Where(callback => callback.Phase == phase)
            .Select(callback => "        " + MethodMeta.EmitInvocation(
                callback.Name, callback.IsStatic, callback.IsValueType, callback.PassArguments
                    ? (phase is CallbackPhase.Serializing or CallbackPhase.Serialized
                        ? "ref writer, ref value" : "ref reader, ref value")
                    : "")).NewLine();

    static string EmitCustomFormatters(EquatableArray<MemberShape> members)
    {
        var sb = new StringBuilder();
        foreach (var item in members)
        {
            if (item.CustomFormatter is not { } attribute) continue;
            var arguments = string.Join(
                ", ",
                attribute.Arguments.Select(EmitTypedConstant));
            var initializers = attribute.Initializers
                .Select(static pair => $"@{pair.Name} = {EmitTypedConstant(pair.Value)}")
                .ToArray();
            var initializer = initializers.Length == 0
                ? ""
                : $" {{ {string.Join(", ", initializers)} }}";

            sb.AppendLine(
                $"    static readonly {attribute.FormatterType} __{item.Name}Formatter = " +
                $"new {attribute.AttributeType}({arguments})" +
                $"{initializer}.GetFormatter();");
        }
        return sb.ToString();
    }

    static string EmitTypedConstant(AttributeValueShape constant)
    {
        if (constant.IsNull)
        {
            return "null";
        }

        return constant.Kind switch
        {
            TypedConstantKind.Primitive =>
                Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(
                    constant.Scalar!,
                    quoteStrings: true,
                    useHexadecimalNumbers: false),
            TypedConstantKind.Enum =>
                $"({constant.TypeName})" +
                Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(
                    constant.Scalar!,
                    quoteStrings: false,
                    useHexadecimalNumbers: false),
            TypedConstantKind.Type =>
                $"typeof({constant.TypeName})",
            TypedConstantKind.Array =>
                $"new {constant.TypeName}[]" +
                $" {{ {string.Join(", ", constant.Elements.Select(EmitTypedConstant))} }}",
            _ => throw new InvalidOperationException(
                $"Unsupported custom formatter attribute argument: {constant.Kind}."),
        };
    }

    bool HasUserStaticInitialization()
        => Members.Any(member => member.Kind == MemberKind.CustomFormatter) ||
           Symbol.GetMembers().Any(member =>
               member is IMethodSymbol method && method.IsStatic &&
               (method.MethodKind == MethodKind.StaticConstructor ||
                method.Name == "StaticConstructor" && method.Parameters.Length == 0 &&
                method.DeclaringSyntaxReferences.Any(reference =>
                    reference.GetSyntax() is MethodDeclarationSyntax declaration &&
                    (declaration.Body is not null || declaration.ExpressionBody is not null))) ||
               member is IFieldSymbol field && field.IsStatic && !field.IsConst &&
               field.DeclaringSyntaxReferences.Any(reference =>
                   reference.GetSyntax() is VariableDeclaratorSyntax { Initializer: not null }) ||
               member is IPropertySymbol property && property.IsStatic &&
               property.DeclaringSyntaxReferences.Any(reference =>
                   reference.GetSyntax() is PropertyDeclarationSyntax { Initializer: not null }));

    string? GetSelfFactoryRootName()
        => HasUserStaticInitialization() ? null : GetFactoryRootName(Symbol, "__SharpPackPreserveSelfFactoryRoots");

    internal static string GetFactoryRootName(INamedTypeSymbol type, string stem)
    {
        // Avoid rebinding existing unqualified names, such as captured
        // primary-constructor parameters and names imported by using static.
        var names = new HashSet<string>(StringComparer.Ordinal) { type.Name };
        foreach (var member in type.GetAllMembers())
        {
            names.Add(member.Name);
        }
        foreach (var reference in type.DeclaringSyntaxReferences)
        {
            foreach (var token in reference.GetSyntax().DescendantTokens())
            {
                if (token.IsKind(SyntaxKind.IdentifierToken) && token.ValueText.StartsWith(stem, StringComparison.Ordinal))
                {
                    names.Add(token.ValueText);
                }
            }
        }

        var name = stem;
        while (names.Contains(name) || names.Contains(name + "Value"))
        {
            name += "_";
        }
        return name;
    }

    internal static string EmitFactoryRootRead(string? name)
        => name is null ? "" : $"        var {name} = {name}Value;";

    string EmitSelfFactoryRoots(string? name, bool includeContextFactory)
        => name is not null
            ? EmitFactoryRootField(name, TypeName, includeContextFactory)
            : $$"""
    static {{Symbol.Name}}()
    {
        StaticConstructor();
{{EmitFactoryPreservation("        ", TypeName, includeContextFactory)}}
    }
""";

    internal static string EmitFactoryRootField(string name, string typeName, bool includeContextFactory)
        => $$"""
    private static readonly bool {{name}}Value = {{name}}();
    private static bool {{name}}()
    {
{{EmitFactoryPreservation("        ", typeName, includeContextFactory)}}
        return true;
    }
""";

    static string EmitFactoryPreservation(string indent, string type, bool includeContextFactory)
        => $"{indent}global::SharpPack.SharpPackSerializer.PreserveFormatterFactory<{type}>();" +
            (includeContextFactory
                ? $"\n{indent}global::SharpPack.SharpPackSerializer.PreserveContextFormatterFactory<{type}>();"
                : "");

    // The deserialization API retains model static constructors. Those roots
    // and the first factory creation retain typed dependencies without relying
    // on Roslyn's private explicit-interface metadata spelling.
    string EmitAotFormatterRoots(string indent)
    {
        var formatterTypes = new SortedSet<string>(StringComparer.Ordinal);
        var factoryTypes = new SortedDictionary<string, bool>(StringComparer.Ordinal);
        var contextFactory = reference.Compilation.GetTypeByMetadataName("SharpPack.ISharpPackContextFormatterFactory`1");

        foreach (var member in Members)
        {
            AddFormatterTypes(member.MemberType);
        }

        var sb = new StringBuilder();
        // Factory methods are needed by trimmed JIT as well as NativeAOT.
        foreach (var entry in factoryTypes)
        {
            sb.AppendLine(EmitFactoryPreservation(indent, entry.Key, entry.Value));
        }
        if (formatterTypes.Count != 0)
        {
            sb.AppendLine(
                $"{indent}if (!global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported)");
            sb.AppendLine($"{indent}{{");
            foreach (var formatterType in formatterTypes)
            {
                sb.AppendLine(
                    $"{indent}    global::System.GC.KeepAlive(new {formatterType}());");
            }
            sb.AppendLine($"{indent}}}");
        }
        return sb.ToString().TrimEnd('\r', '\n');

        void AddFormatterTypes(ITypeSymbol type)
        {
            if (reference.KnownTypes.GetNonDefaultFormatterName(type) is { } formatter)
            {
                formatterTypes.Add(formatter);
            }

            if (type is INamedTypeSymbol model &&
                type.TryGetSharpPackableType(reference, out var generateType, out _) &&
                generateType != GenerateType.NoGenerate)
            {
                // This compilation can add a factory to a source model; for
                // referenced assemblies, check the interface actually shipped.
                var willGenerateContextFactory =
                    SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, reference.Compilation.Assembly) &&
                    generateType is (GenerateType.Object or GenerateType.VersionTolerant or GenerateType.CircularReference) &&
                    !type.ContainsAttribute(reference.SharpPackUnionAttribute);
                var hasContextFactory = model.AllInterfaces.Any(i =>
                    SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, contextFactory) &&
                    SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], type));
                factoryTypes[type.FullyQualifiedToString()] = willGenerateContextFactory || hasContextFactory;
            }

            if (type is IArrayTypeSymbol array)
            {
                AddFormatterTypes(array.ElementType);
            }
            else if (type is INamedTypeSymbol named)
            {
                foreach (var argument in named.TypeArguments)
                {
                    AddFormatterTypes(argument);
                }
            }
        }
    }

    string EmitSerializeBody(MemberMeta[] members)
    {
        if (this.GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference)
        {
            return members.All(x =>
                x.Kind is MemberKind.Unmanaged
                    or MemberKind.String
                    or MemberKind.Enum
                    or MemberKind.UnmanagedArray
                    or MemberKind.UnmanagedNullable
                    or MemberKind.Blank)
                ? EmitVersionTorelantSerializeBodyOptimized(members)
                : EmitVersionTorelantSerializeBody(
                    members, honorFormatterOverrides: false);
        }

        return EmitObjectSerializeBody(members, honorFormatterOverrides: false);
    }

    string EmitExactSizeSerializeMethod()
    {
        var captureMembers = Members
            .Select((member, index) => member.Kind == MemberKind.String
                ? $"""
        var __value{index} = this.@{member.Name};
        var __utf8Length{index} = __value{index} is null || __value{index}.Length == 0
            ? 0
            : global::System.Text.Encoding.UTF8.GetByteCount(__value{index});
"""
                : $"        var __value{index} = this.@{member.Name};")
            .NewLine();
        var sizeTerms = Members
            .Select((member, index) => member.Kind switch
            {
                MemberKind.Unmanaged or
                MemberKind.Enum or
                MemberKind.UnmanagedNullable =>
                    $"global::System.Runtime.CompilerServices.Unsafe.SizeOf<{member.MemberType.FullyQualifiedToString()}>()",
                MemberKind.String =>
                    $"(__value{index} is null || __value{index}.Length == 0 ? 4L : (long)__utf8Length{index} + 8)",
                MemberKind.UnmanagedArray =>
                    $"(__value{index} is null || __value{index}.Length == 0 ? 4L : (long)__value{index}.Length * global::System.Runtime.CompilerServices.Unsafe.SizeOf<{((IArrayTypeSymbol)member.MemberType).ElementType.FullyQualifiedToString()}>() + 4)",
                _ => throw new InvalidOperationException(),
            });
        var writeMembers = Members
            .Select((member, index) => member.Kind switch
            {
                MemberKind.Unmanaged or MemberKind.Enum =>
                    $"        writer.WriteUnmanaged(__value{index});",
                MemberKind.UnmanagedNullable =>
                    $"        writer.DangerousWriteUnmanaged(__value{index});",
                MemberKind.String =>
                    $"        writer.WriteUtf8Exact(__value{index}, __utf8Length{index});",
                MemberKind.UnmanagedArray =>
                    $"        writer.WriteUnmanagedArray(__value{index});",
                _ => throw new InvalidOperationException(),
            })
            .NewLine();
        var sizeExpression = string.Join(
            " + " + Environment.NewLine + "            ",
            sizeTerms);

        return $$"""

    [global::SharpPack.CompilerServices.Preserve]
    byte[] global::SharpPack.ISharpPackExactSizeSerializable<{{TypeName}}>.SerializeExact()
    {
{{captureMembers}}
        var size = 1L +
            {{sizeExpression}};
        if ((ulong)size > (ulong)global::System.Array.MaxLength)
        {
            global::SharpPack.SharpPackSerializationException.ThrowSizeOverflow();
        }
        var buffer = global::System.GC.AllocateUninitializedArray<byte>((int)size);
        var bufferWriter =
            new global::SharpPack.Internal.SharpPackExactArrayBufferWriter(buffer);
        var writer = global::SharpPack.SharpPackSerializer.CreateExactWriter(
            ref bufferWriter);
        writer.WriteObjectHeader({{Members.Length}});
{{writeMembers}}
        writer.Flush();
        return bufferWriter.GetFilledBuffer();
    }
""";
    }

    string EmitFormatterOverrideMethods(string contextFormatterTypeName, TypeShape shape, MemberMeta[] members)
    {
        var writerCondition =
            EmitFormatterOverrideDependencyCondition(members, "writer");
        if (writerCondition.Length == 0)
        {
            return "";
        }

        var overrideSerializeBody =
            GenerateType is GenerateType.VersionTolerant or GenerateType.CircularReference
                ? EmitVersionTorelantSerializeBody(
                    members, honorFormatterOverrides: true)
                : EmitObjectSerializeBody(
                    members, honorFormatterOverrides: true);
        var overrideDeserializeBody = EmitDeserializeBodyCore(
            members, honorFormatterOverrides: true);
        var nullable = IsValueType ? "" : "?";
        var serializeHelperName =
            GetFormatterOverrideHelperName(serialize: true);
        var deserializeHelperName =
            GetFormatterOverrideHelperName(serialize: false);

        return $$"""

    [global::System.Runtime.CompilerServices.MethodImpl(
        global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    static void {{serializeHelperName}}<TBufferWriter>(
        ref global::SharpPack.SharpPackWriter<TBufferWriter> writer,
        scoped ref {{TypeName}}{{nullable}} value)
        where TBufferWriter : global::System.Buffers.IBufferWriter<byte>
    {
{{EmitCallbacks(shape, CallbackPhase.Serializing)}}
{{overrideSerializeBody}}
    END:
{{EmitCallbacks(shape, CallbackPhase.Serialized)}}
        return;
    }

    [global::System.Runtime.CompilerServices.MethodImpl(
        global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    static void {{deserializeHelperName}}(
        ref global::SharpPack.SharpPackReader reader,
        scoped ref {{TypeName}}{{nullable}} value)
    {
{{EmitCallbacks(shape, CallbackPhase.Deserializing)}}
{{overrideDeserializeBody}}
    END:
{{EmitCallbacks(shape, CallbackPhase.Deserialized)}}
        return;
    }

    [global::SharpPack.CompilerServices.Preserve]
    sealed class {{contextFormatterTypeName}}
        : global::SharpPack.SharpPackFormatter<{{TypeName}}>,
          global::SharpPack.ISharpPackContextOverrideFormatter
    {
        public override void Serialize<TBufferWriter>(
            ref global::SharpPack.SharpPackWriter<TBufferWriter> writer,
            scoped ref {{TypeName}}{{nullable}} value)
            => {{serializeHelperName}}(ref writer, ref value);

        public override void Deserialize(
            ref global::SharpPack.SharpPackReader reader,
            scoped ref {{TypeName}}{{nullable}} value)
            => {{deserializeHelperName}}(ref reader, ref value);
    }
""";
    }

